export interface DocItem {
  id: string;
  field1: string; // Dynamic label depending on doc
  field2?: string; // Dynamic label depending on doc
  field3?: string;
  field4?: string;
  field5?: string;
  field6?: string;
  field7?: string;

  // Process Card specific fields
  processType?: 'COPs' | 'MOPs' | 'SOPs';
  processGoal?: string;
  field6_docs?: string;

  // SWOT or RISK_MANAGEMENT specific fields
  type?: 'S' | 'W' | 'O' | 'T' | 'context' | 'risk_and_opp' | 'lesson' | 'clause_link' | 'strategic_risk'; // Strengths, Weaknesses, Opportunities, Threats or risk types
  weight?: number; // SWOT weight
  rating?: number; // SWOT rating
  
  // Risk/FMEA specific fields
  severity?: number; // Severity (1-10)
  occurrence?: number; // Occurrence (1-10)
  detection?: number; // Detection (1-10)
  
  // Calibration specific fields
  refValue?: number; // Standard reference value
  readValue?: number; // Measured reading
  mpe?: number; // Maximum Permissible Error (MPE)
  
  // KPI/Objectives specific fields
  target?: number; // Target level
  actual?: number; // Actual current level
  unit?: string; // Unit (e.g. %, PPM, hours)
  clauseId?: string; // Standard clause ID reference
  
  // SPC specific fields
  usl?: number; // Upper Specification Limit
  lsl?: number; // Lower Specification Limit
  measurements?: string; // Comma-separated measurements (e.g. "12.01, 11.98, ...")
  
  // COQ (Cost of Quality) specific fields
  coqCategory?: 'prevention' | 'appraisal' | 'internal_failure' | 'external_failure';
  coqAmount?: number; // Quality cost amount in Rials

  // MSA (Measurement System Analysis) specific fields
  evValue?: number; // Equipment Variation (EV)
  avValue?: number; // Appraiser Variation (AV)
  ndiv?: number; // Number of distinct categories

  [key: string]: any; // Allow dynamic columns and custom data keys
}

